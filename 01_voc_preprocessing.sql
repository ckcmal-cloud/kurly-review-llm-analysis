-- 2. 요약 결과 생성 (Review Summary 및 Category Summary 도출)
-- Python Line 1018-1025: summary 집계 로직 재현
CREATE TABLE voc_category_summary AS
SELECT 
    segment,
    category,
    subtype,
    COUNT(1) AS review_count,
    COUNT(DISTINCT product_no) AS product_count,
    ROUND(AVG(review_length), 1) AS avg_length
FROM user_voc_base
GROUP BY 
    segment,
    category,
    subtype;
